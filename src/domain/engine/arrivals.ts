import type { ProfilePoint, Workload } from "../model/project";
import type { RandomSource } from "../random/random-source";

/**
 * Target request rate at `atSec`: linear between profile points, flat before
 * the first point and after the last (MVP design §3.4).
 */
export function rateAt(
  profile: readonly ProfilePoint[],
  atSec: number,
): number {
  const index = profile.findIndex((point) => atSec <= point.atSec);
  const point = profile[index];
  // Past the last point (index -1), or an empty profile.
  if (point === undefined) return profile.at(-1)?.requestsPerSec ?? 0;
  const previous = profile[index - 1];
  if (previous === undefined || point.atSec === previous.atSec) {
    return point.requestsPerSec;
  }
  return interpolate({ from: previous, to: point, atSec });
}

interface Interpolation {
  readonly from: ProfilePoint;
  readonly to: ProfilePoint;
  /** Between `from.atSec` and `to.atSec`. */
  readonly atSec: number;
}

/** The rate on the straight line between two profile points. */
function interpolate({ from, to, atSec }: Interpolation): number {
  const share = (atSec - from.atSec) / (to.atSec - from.atSec);
  return (
    from.requestsPerSec + share * (to.requestsPerSec - from.requestsPerSec)
  );
}

export interface ArrivalProcessInput {
  readonly workload: Workload;
  /** Draws arrival times. */
  readonly timing: RandomSource;
  /**
   * Draws which workflow runs. A separate stream, so changing the mix doesn't
   * move the arrival times.
   */
  readonly choice: RandomSource;
}

/**
 * When users send requests, and which workflow each one runs. Arrivals are a
 * Poisson process whose rate follows the workload's profile (an open model:
 * users keep arriving however slow the system gets).
 *
 * The rate changes over time, so arrivals are generated by thinning: draw
 * candidate arrivals at the profile's peak rate, then keep each one with
 * probability rate(t) / peak rate.
 */
export class ArrivalProcess {
  private readonly workload: Workload;
  private readonly timing: RandomSource;
  private readonly choice: RandomSource;
  private readonly peakPerSec: number;
  private readonly endMs: number;
  private readonly totalWeight: number;

  constructor({ workload, timing, choice }: ArrivalProcessInput) {
    this.workload = workload;
    this.timing = timing;
    this.choice = choice;
    this.peakPerSec = Math.max(
      0,
      ...workload.profile.map((p) => p.requestsPerSec),
    );
    this.endMs = workload.durationSec * 1000;
    this.totalWeight = workload.mix.reduce((sum, m) => sum + m.weight, 0);
  }

  /** The first arrival after `afterMs`, or undefined if none before the workload ends. */
  next(afterMs: number): number | undefined {
    if (this.peakPerSec <= 0) return undefined;
    const meanGapMs = 1000 / this.peakPerSec;
    let timeMs = afterMs;
    for (;;) {
      timeMs += -meanGapMs * Math.log(1 - this.timing.next());
      if (timeMs >= this.endMs) return undefined;
      const rate = rateAt(this.workload.profile, timeMs / 1000);
      if (this.timing.next() * this.peakPerSec < rate) return timeMs;
    }
  }

  /** Picks a workflow ID at random, weighted by the mix. */
  pickWorkflow(): string {
    let remaining = this.choice.next() * this.totalWeight;
    for (const entry of this.workload.mix) {
      remaining -= entry.weight;
      if (remaining < 0) return entry.workflowId;
    }
    const last = this.workload.mix[this.workload.mix.length - 1];
    if (last === undefined) throw new Error("The workload's mix is empty");
    return last.workflowId;
  }
}
