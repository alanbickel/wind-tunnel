import type { Workload } from "../model/project";
import type { RandomSource } from "../random/random-source";
import type { ArrivalProcess } from "./arrival-process";
import { rateAt } from "./arrivals";

export interface PoissonArrivalProcessDependencies {
  readonly workload: Workload;
  /** Draws arrival times. */
  readonly timing: RandomSource;
  /**
   * Draws which workflow runs. A separate stream, so changing the mix doesn't
   * move the arrival times.
   */
  readonly choice: RandomSource;
}

/**
 * An `ArrivalProcess` whose arrivals are a Poisson process, with a rate that
 * follows the workload's profile. It is an open model: users keep arriving
 * however slow the system gets.
 *
 * The rate changes over time, so arrivals are generated by thinning: draw
 * candidate arrivals at the profile's peak rate, then keep each one with
 * probability rate(t) / peak rate.
 */
export class PoissonArrivalProcess implements ArrivalProcess {
  private readonly workload: Workload;
  private readonly timing: RandomSource;
  private readonly choice: RandomSource;
  private readonly peakPerSec: number;
  private readonly endMs: number;
  private readonly totalWeight: number;

  constructor({ workload, timing, choice }: PoissonArrivalProcessDependencies) {
    this.workload = workload;
    this.timing = timing;
    this.choice = choice;
    this.peakPerSec = Math.max(
      0,
      ...workload.profile.map((p) => p.requestsPerSec),
    );
    this.endMs = workload.durationMs;
    this.totalWeight = workload.mix.reduce((sum, m) => sum + m.weight, 0);
  }

  /** The first arrival after `afterMs`, or undefined if none before the workload ends. */
  next(afterMs: number): number | undefined {
    if (this.peakPerSec <= 0) return undefined;
    const meanGapMs = 1000 / this.peakPerSec;
    let timeMs = afterMs;
    for (;;) {
      timeMs += -meanGapMs * Math.log(1 - this.timing.next());
      if (timeMs >= this.endMs) return undefined;
      const rate = rateAt(this.workload.profile, timeMs);
      if (this.timing.next() * this.peakPerSec < rate) return timeMs;
    }
  }

  /** Picks a workflow ID at random, weighted by the mix. */
  pickWorkflow(): string {
    let remaining = this.choice.next() * this.totalWeight;
    for (const entry of this.workload.mix) {
      remaining -= entry.weight;
      if (remaining < 0) return entry.workflowId;
    }
    const last = this.workload.mix[this.workload.mix.length - 1];
    if (last === undefined) throw new Error("The workload's mix is empty");
    return last.workflowId;
  }
}
